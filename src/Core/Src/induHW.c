/* Watchdog del CPU: si el firmware se cuelga ~1 s, el micro se reinicia.
 * LSI ~40 kHz / 64 = 625 Hz -> 625 cuentas = 1 s (0,66..1,5 s segun el LSI).
 * Al reiniciarse el CPU deja de escribir y los modulos de salidas pasan
 * solos a estado seguro (SALIDAS_TIMEOUT_MS en Modulo_OUT). */
void induWatchdogInit(void)
{
  __HAL_DBGMCU_FREEZE_IWDG();   /* se detiene con el depurador en pausa */
  hiwdg.Instance = IWDG;
  hiwdg.Init.Prescaler = IWDG_PRESCALER_64;
  hiwdg.Init.Reload = 625;
  if (HAL_IWDG_Init(&hiwdg) != HAL_OK)
  {
    Error_Handler();
  }
}

void induWatchdogRefresh(void)
{
  if (hiwdg.Instance != 0)
    HAL_IWDG_Refresh(&hiwdg);
}
